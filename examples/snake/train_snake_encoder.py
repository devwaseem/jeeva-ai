"""Train a ModernBERT Jeeva artifact for the unchanged Snake game.

Generate current-format data first when needed:
    uv run python -m examples.snake.generate_data \
        --train-samples 300 --eval-samples 60 \
        --output-dir /tmp/jeeva-snake-data

Then train:
    uv run python -m examples.snake.train_snake_encoder \
        --train-data /tmp/jeeva-snake-data/snake_train.jsonl \
        --eval-data /tmp/jeeva-snake-data/snake_eval.jsonl
"""

from __future__ import annotations

import argparse
from pathlib import Path

from examples.snake.play_snake import DirectionDecision
from jeeva import DecisionModel, FitConfig


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Train a bidirectional encoder model for Snake.")
    parser.add_argument(
        "--model",
        default="answerdotai/ModernBERT-base",
        help="Hugging Face encoder model ID.",
    )
    parser.add_argument(
        "--train-data",
        type=Path,
        default=Path("examples/snake/data/snake_train.jsonl"),
        help="Training JSONL generated by examples.snake.generate_data.",
    )
    parser.add_argument(
        "--eval-data",
        type=Path,
        default=Path("examples/snake/data/snake_eval.jsonl"),
        help="Held-out JSONL used for validation and calibration.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("examples/snake/checkpoints/snake_encoder"),
        help="Destination for the trained Jeeva encoder artifact.",
    )
    parser.add_argument("--epochs", type=int, default=5)
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--max-length", type=int, default=512)
    parser.add_argument(
        "--learning-rate",
        type=float,
        default=None,
        help="Override Jeeva's encoder learning-rate default.",
    )
    parser.add_argument(
        "--adaptation",
        choices=("auto", "head", "full", "lora"),
        default="auto",
        help="Auto selects LoRA; head explicitly freezes the encoder backbone.",
    )
    parser.add_argument(
        "--device",
        default="auto",
        help="Training device, such as auto, mps, cuda, or cpu.",
    )
    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()

    if not args.train_data.is_file():
        parser.error(f"training dataset not found: {args.train_data}")
    if not args.eval_data.is_file():
        parser.error(f"evaluation dataset not found: {args.eval_data}")
    if args.output_dir.exists() and (
        not args.output_dir.is_dir() or any(args.output_dir.iterdir())
    ):
        parser.error(f"output directory must be absent or empty: {args.output_dir}")

    config = FitConfig(
        epochs=args.epochs,
        learning_rate=args.learning_rate,
        adaptation=args.adaptation,
        batch_size=args.batch_size,
        max_length=args.max_length,
    )

    base = DecisionModel(
        args.model,
        architecture="encoder",
        device=args.device,
    )
    trained = base.fit(
        args.train_data,
        schema=DirectionDecision,
        validation=args.eval_data,
        config=config,
    )
    artifact = trained.save(args.output_dir)

    print(f"\nArtifact saved: {artifact}")
    print(
        "Run: uv run python -m examples.snake.play_snake "
        f"--model {artifact} --device {args.device} --steps 200"
    )


if __name__ == "__main__":
    main()
